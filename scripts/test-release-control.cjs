'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { classify, inspect, receiptFiles, packagePath, preflight, runChild, runPackage } = require('./release-control.cjs');
const base = fs.mkdtempSync(path.join(os.tmpdir(), 'release-control-test-'));
const create = (name, code) => { const p = path.join(base, name); fs.mkdirSync(p); fs.writeFileSync(path.join(p, 'publish.cjs'), code); return p; };
const json = p => JSON.parse(fs.readFileSync(p));
(async () => {
  assert.equal(classify({ cause: { code: 'ENOTFOUND' } }).category, 'dns');
  assert.equal(classify({ code: 'EPERM' }).category, 'permission');
  assert.equal(classify({ code: 'AUTH_EXPIRED' }).category, 'authentication');
  assert(!JSON.stringify(classify(new Error('secret token'))).includes('secret token'));
  const stages = [];
  assert.throws(() => preflight(false, stage => { stages.push(stage); if (stage === 'dns') throw { code: 'ENOTFOUND' }; }));
  assert.deepEqual(stages, ['credentials', 'dns']);
  let first = true; const refreshed = [];
  preflight(true, stage => { refreshed.push(stage); if (stage === 'credentials' && first) { first = false; throw { code: 'AUTH_EXPIRED' }; } });
  assert.deepEqual(refreshed, ['credentials', 'refresh-login', 'credentials', 'dns', 'public-http', 'cos-read', 'database-read']);
  assert.throws(() => packagePath('../wrong', base), /INVALID_PACKAGE/);
  assert.throws(() => packagePath('offline-test', base), /INVALID_PACKAGE/);
  assert.throws(() => receiptFiles({ units: 71 }), /PACKAGE_SPECIFIC/);
  assert.throws(() => receiptFiles({ files: [{ key: '../private', sha256: 'a'.repeat(64) }] }), /UNSUPPORTED/);
  assert.equal(receiptFiles({ objects: [{ key: 'index.html', sha256: 'a'.repeat(64) }] }).length, 1);
  const opts = { lockDir: base, preflight: () => {} };
  const ok = create('success', "require('fs').writeFileSync(__dirname+'/receipt.json', JSON.stringify({at: new Date().toISOString(), files: []}));");
  assert.equal((await runPackage(ok, false, false, 2000, opts)).state, 'publisher-completed-with-receipt');
  assert.equal(inspect(ok).state, 'receipt-present');
  assert.equal(inspect(ok).liveVerifiedNow, false);
  await assert.rejects(runPackage(ok, false, false, 2000, opts), /RECEIPT_EXISTS/);
  const blocked = create('blocked', "require('fs').writeFileSync(__dirname+'/WRITTEN', 'wrong');");
  await assert.rejects(runPackage(blocked, false, false, 1000, { ...opts, preflight() { throw Object.assign(new Error('ENOTFOUND'), { code: 'ENOTFOUND', stage: 'dns' }); } }), /ENOTFOUND/);
  assert(!fs.existsSync(path.join(blocked, 'WRITTEN')));
  assert.equal(json(path.join(blocked, 'release-control-state.json')).state, 'blocked-before-publisher');
  const partial = create('partial', "const fs=require('fs'); fs.writeFileSync(__dirname+'/uploaded-marker', 'partial'); fs.writeFileSync(__dirname+'/last-error.json', JSON.stringify({stage:'transaction-read-material',error:'ERR_ASSERTION',reason:'private-secret'})); process.exit(1);");
  await assert.rejects(runPackage(partial, false, false, 1000, opts), /PUBLISH_FAILED/);
  assert.equal(json(path.join(partial, 'release-control-state.json')).state, 'failed-or-partial-needs-readback');
  assert.equal(json(path.join(partial, 'release-control-state.json')).publisherDiagnostic.stage, 'transaction-read-material');
  assert(!fs.readFileSync(path.join(partial, 'release-control-state.json'), 'utf8').includes('private-secret'));
  const replaced = create('ielts-unit2-tail72-20261106', 'process.exit(0);');
  await assert.rejects(runPackage(replaced, false, false, 1000, opts), /PACKAGE_SUPERSEDED/);
  const missing = create('no-receipt', 'process.exit(0);');
  await assert.rejects(runPackage(missing, false, false, 1000, opts), /NO_NEW_RECEIPT/);
  fs.writeFileSync(path.join(missing, 'receipt.json'), '{}');
  await assert.rejects(runPackage(missing, false, true, 1000, opts), /NO_NEW_RECEIPT/);
  const hang = create('hang', 'setInterval(() => {}, 1000);');
  assert.equal((await runChild(path.join(hang, 'publish.cjs'), 100)).timedOut, true);
  fs.writeFileSync(path.join(base, 'release-control.lock'), '{}');
  await assert.rejects(runPackage(hang, false, false, 1000, opts), /ANOTHER_RELEASE/);
  assert(fs.existsSync(path.join(base, 'release-control.lock')));
  console.log('release-control: preflight, refresh, redaction, receipt provenance, partial writes, timeouts and locking passed');
})().finally(() => fs.rmSync(base, { recursive: true, force: true })).catch(e => { console.error(e); process.exitCode = 1; });
